// Keep the category id so a home card can jump to /menu#starters and land in the right place.
export function getFeaturedDishes() {
  return menuCategories.flatMap((category) =>
    category.items
      .filter((item) => item.featured)
      .map((item) => ({
        ...item,
        categoryId: category.id,
        categoryTitle: category.title,
      })),
  )
}
